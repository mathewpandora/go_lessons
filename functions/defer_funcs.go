func fn56() {
	i := 0
	fmt.Println("Указатель исходной i", &i)
	defer func() {
		fmt.Println("Указатель в первой функции  i", &i)
		fmt.Println("Выполнится отложенно", i) //так выведится 5 спросить почему? Скорее всего он не находит ее в рамках своего бока лезет выше и находит i = 5
	}()

	defer func(i int) {
		fmt.Println("указатель во второй функции i", &i)
		fmt.Println("Выполнится отложенно2", i) //так выведится 5 спросить почему? Скорее всего он не находит ее в рамках своего бока лезет выше и находит i = 5
	}(i)
	i = 5 //они кустати кажется выполняются стеком сложили и потом начиная с послденей операции помчит (в обратном пордядке) (спросить это так?)
}

func WTF() (i int) { //Если у возвращаемого значения есть имя (i int) — defer видит эту коробку и может её изменить.
	i = 5
	defer func() { i++ }()
	return i //ОНА ОТДАСТ 6!!!!!!!!!!!!

}

func WTF2() int { //Если у возвращаемого значения нет имени (int) — return копирует значение в коробку, и потом defer уже трогает другую переменную.
	i := 5
	defer func() { i++ }()
	return i // вернёт 5, потому что return копирует значение i
}

//Как мы говорили, defer выполняется всегда, когда функция завершается, даже если у нас произошла паника. Однако, если мы выйдем из программы вовсе, тогда defer не выполнится.
